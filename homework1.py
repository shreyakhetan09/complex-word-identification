def _glove_vec(word, wv):
    if word in wv:
        return np.asarray(wv[word], dtype=float)
    parts = [p for p in re.split(r"[^a-z]+", word) if p in wv]
    if parts:
        return np.mean([wv[p] for p in parts], axis=0)
    return np.zeros(50)


def _sent_vec(sentence, wv):
    toks = re.findall(r"[a-z]+", sentence.lower())
    vecs = [wv[t] for t in toks if t in wv]
    return np.mean(vecs, axis=0) if vecs else np.zeros(50)


def _cosine(a, b):
    na, nb = np.linalg.norm(a), np.linalg.norm(b)
    if na == 0 or nb == 0:
        return 0.0
    return float(np.dot(a, b) / (na * nb))


def _max_cons(word):
    best = run = 0
    for ch in word:
        if ch.isalpha() and ch not in VOWELS:
            run += 1
            best = max(best, run)
        else:
            run = 0
    return best


def _mark(word, sent):
    if not sent:
        return word
    pat = re.compile(re.escape(word), re.IGNORECASE)
    marked, n = pat.subn(lambda m: "[[" + m.group(0) + "]]", sent, count=1)
    return marked if n else sent + " [[" + word + "]]"


